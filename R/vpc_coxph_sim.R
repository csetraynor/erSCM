#' Simulation-Based Visual Predictive Check for Cox SCM Models
#'
#' Performs a simulation-based visual predictive check (VPC) for a Cox
#' proportional hazards model fit by \code{\link{scm_coxph}}. Replicate event
#' datasets are simulated under coefficient uncertainty, Kaplan-Meier curves are
#' recomputed within strata of \code{covariate_term}, and the simulated
#' pointwise quantile band is overlaid with the observed Kaplan-Meier curve.
#'
#' @details
#' \code{vpc_coxph_sim()} is complementary to \code{\link{vpc_coxph}}.
#' \code{vpc_coxph()} is an analytical confidence-band diagnostic based on
#' \code{survival::survfit()} at reference profiles. \code{vpc_coxph_sim()}
#' instead simulates outcomes and compares observed versus simulated survival
#' summaries at common time points.
#'
#' @section Simulation mechanism:
#' For each of \code{n_sim} replicates, a coefficient vector is drawn from
#' \eqn{\mathcal{N}(\hat{\beta}, \widehat{\mathrm{Var}}(\hat{\beta}))} using
#' the Cholesky factor of \code{stats::vcov(fit$final_model)} and
#' \code{stats::rnorm()}. Event times are then generated by inverse transform
#' sampling from a fixed Breslow baseline cumulative hazard derived from the
#' fitted model. Follow-up censoring is fixed to each subject's observed
#' follow-up time, so simulated outcomes reflect coefficient uncertainty plus
#' event-time stochasticity under the observed follow-up design.
#'
#' @section Reproducibility:
#' Randomness is controlled by \code{seed}. Internally the function derives one
#' independent \code{"L'Ecuyer-CMRG"} stream per replicate via
#' \code{.make_rng_streams()}, so simulated quantiles are identical for a given
#' \code{seed} whether \code{parallel = FALSE} or \code{parallel = TRUE}. The
#' caller's RNG kind and \code{.Random.seed} are restored on exit.
#'
#' @section Interpretation:
#' The band is a pointwise predictive envelope for the chosen Kaplan-Meier
#' summary under a fixed baseline hazard and fixed observed censoring pattern.
#' It does not represent full uncertainty from baseline-hazard re-estimation,
#' censoring-model uncertainty, or simultaneous-time coverage.
#'
#' @section Limitations:
#' - Categorical and numeric (\code{n_bins >= 1}) stratification are both supported.
#'   Numeric binning uses \code{ggplot2::cut_number()}, so each bin contains
#'   approximately equal numbers of subjects.
#' - Time-dependent Cox model forms are not supported in this release. Models
#'   using \code{tt()}, \code{strata()}, \code{cluster()}, or start-stop
#'   \code{Surv()} responses abort with an informative error.
#'
#' @param fit An object of class \code{eres_scm_coxph} returned by
#'   \code{\link{scm_coxph}}.
#' @param covariate_term Character; main-effect covariate used to define
#'   stratification groups for observed and simulated Kaplan-Meier summaries.
#' @param n_bins Integer >= 1; number of quantile strata for a numeric
#'   \code{covariate_term}. When \code{n_bins = 1} (the only sensible value for
#'   a factor/character covariate) the entire cohort is treated as one group
#'   (\code{"Overall"}). For a numeric covariate, \code{n_bins > 1} divides
#'   subjects into equal-count quantile bins via \code{ggplot2::cut_number()},
#'   and separate observed/simulated KM curves are produced per bin. Default 4.
#' @param n_sim Integer; number of simulation replicates. Default 500. For
#'   formal reporting, consider \code{n_sim >= 1000}.
#' @param probs Numeric vector of length 2 or 3 with values in \code{(0, 1)}.
#'   Length 3 (default \code{c(0.05, 0.5, 0.95)}) adds a median simulated curve.
#' @param time_grid Optional numeric vector of time points where observed and
#'   simulated curves are evaluated. Default \code{NULL} uses unique observed
#'   event times, clamped to \code{[0, max(observed event time)]}.
#' @param seed Integer; master RNG seed. Default 42.
#' @param parallel Logical; if \code{TRUE}, replicates are dispatched with
#'   \code{future.apply::future_lapply()} using per-replicate streams from
#'   \code{.make_rng_streams()}. Default \code{FALSE}.
#' @param plot Logical; if \code{TRUE} (default), returns a \code{ggplot}
#'   object; if \code{FALSE}, returns the computed data frame.
#'
#' @return If \code{plot = TRUE}, a \code{ggplot2} object with observed
#'   Kaplan-Meier step curves overlaid on the simulated pointwise prediction
#'   ribbon and optional median line. If \code{plot = FALSE}, a data frame with
#'   columns \code{strata}, \code{time}, \code{sim_lo}, \code{sim_mid},
#'   \code{sim_hi}, \code{obs_est}, \code{obs_lo}, and \code{obs_hi}.
#'
#' @seealso \code{\link{vpc_coxph}}, \code{\link{vpc_logistic}},
#'   \code{\link{plot_cox_terms}}, \code{\link{scm_coxph}}
#'
#' @examples
#' \donttest{
#' data(demo_eres)
#' demo_eres$SEX <- as.factor(demo_eres$SEX)
#' fit <- scm_coxph(
#'   eres_data = demo_eres, exposure_vars = "CMAXss", covariates = c("AGE", "WT"),
#'   dv_col = "sim_status", time_col = "sim_time", significance_level = c(0.2, 0.2)
#' )
#' vpc_coxph_sim(fit, covariate_term = "CMAXss", n_bins = 4, n_sim = 200)
#' }
#'
#' @importFrom stats vcov coef rnorm runif quantile model.frame
#' @export
vpc_coxph_sim <- function(fit, covariate_term, n_bins = 4, n_sim = 500,
                          probs = c(0.05, 0.5, 0.95), time_grid = NULL,
                          seed = 42L, parallel = FALSE, plot = TRUE) {

  if (!inherits(fit, "eres_scm_coxph")) {
    cli::cli_abort(c(
      "{.arg fit} must be an {.cls eres_scm_coxph} object from {.fun scm_coxph}.",
      "x" = "Got an object of class {.cls {class(fit)}}."
    ))
  }
  if (is.null(fit$final_model)) {
    cli::cli_abort(c(
      "{.arg fit} has no {.field final_model}.",
      "i" = "No model was selected, so there is nothing to check."
    ))
  }
  if (!is.character(covariate_term) || length(covariate_term) != 1L) {
    cli::cli_abort("{.arg covariate_term} must be a single variable name.")
  }
  if (grepl(":", covariate_term, fixed = TRUE)) {
    main_effects <- get_main_effect_columns(fit$metadata$finalRelation)
    cli::cli_abort(c(
      "{.fun vpc_coxph_sim} does not support interaction terms as {.arg covariate_term}.",
      "i" = "Use a main-effect variable name, e.g. one of: {.val {main_effects}}."
    ))
  }
  if (!is.numeric(n_bins) || length(n_bins) != 1L || is.na(n_bins) ||
      n_bins != as.integer(n_bins) || n_bins < 1) {
    cli::cli_abort("{.arg n_bins} must be a single integer >= 1.")
  }
  if (!is.numeric(n_sim) || length(n_sim) != 1L || is.na(n_sim) ||
      n_sim != as.integer(n_sim) || n_sim < 1L) {
    cli::cli_abort("{.arg n_sim} must be a single positive integer.")
  }
  if (!is.numeric(probs) || !length(probs) %in% c(2L, 3L) ||
      any(is.na(probs)) || any(probs <= 0) || any(probs >= 1)) {
    cli::cli_abort("{.arg probs} must be a numeric vector of length 2 or 3 in (0, 1).")
  }
  probs <- sort(probs)
  has_median <- length(probs) == 3L

  cox_fit <- fit$final_model
  .vpc_coxph_sim_assert_supported_model(cox_fit)

  mf <- stats::model.frame(cox_fit)
  if (!covariate_term %in% colnames(mf)) {
    vars <- setdiff(colnames(mf), c("(weights)", "(offset)", "TIME", "DV"))
    cli::cli_abort(c(
      "{.arg covariate_term} = {.val {covariate_term}} is not a predictor in {.field final_model}.",
      "i" = "Available predictors: {.val {vars}}."
    ))
  }

  y_mat <- cox_fit$y
  if (!is.matrix(y_mat) || ncol(y_mat) < 2L) {
    cli::cli_abort("Internal error: expected a right-censored response matrix in {.field final_model$y}.")
  }

  time_obs <- as.numeric(y_mat[, 1L])
  event_obs <- as.integer(y_mat[, 2L])
  event_times <- time_obs[event_obs == 1L]
  if (length(event_times) == 0L) {
    cli::cli_abort("Observed data have no events; simulation-based Cox VPC requires at least one event.")
  }
  max_event_time <- max(event_times, na.rm = TRUE)

  if (is.null(time_grid)) {
    grid <- sort(unique(event_times))
  } else {
    if (!is.numeric(time_grid) || length(time_grid) < 1L || any(!is.finite(time_grid))) {
      cli::cli_abort("{.arg time_grid} must be a numeric vector of finite values.")
    }
    grid <- sort(unique(as.numeric(time_grid)))
  }
  grid <- grid[grid >= 0 & grid <= max_event_time]
  if (length(grid) == 0L) {
    cli::cli_abort(c(
      "{.arg time_grid} has no usable values after clamping.",
      "i" = "Allowed range is [0, {.val {max_event_time}}]."
    ))
  }

  cov_values <- mf[[covariate_term]]
  is_numeric_cov <- is.numeric(cov_values)
  n_bins <- as.integer(n_bins)
  n_sim <- as.integer(n_sim)

  if (is.factor(cov_values)) {
    strata_levels_raw <- levels(droplevels(cov_values))
    strata_raw <- as.character(cov_values)
  } else if (is.character(cov_values) || is.logical(cov_values)) {
    strata_levels_raw <- sort(unique(as.character(cov_values)))
    strata_raw <- as.character(cov_values)
  } else if (is_numeric_cov && n_bins > 1L) {
    bin_factor <- ggplot2::cut_number(cov_values, n = n_bins)
    strata_levels_raw <- levels(bin_factor)
    strata_raw <- as.character(bin_factor)
  } else {
    # Numeric, n_bins == 1: single "Overall" group
    strata_levels_raw <- "Overall"
    strata_raw <- rep("Overall", length(cov_values))
  }

  var_spec_obj <- fit$var_spec
  cov_label <- get_var_label(var_spec_obj, covariate_term)
  raw_to_disp <- stats::setNames(strata_levels_raw, strata_levels_raw)
  if (!is_numeric_cov) {
    cats <- get_var_categories(var_spec_obj, covariate_term)
    if (!is.null(cats)) {
      if (length(cats) == length(strata_levels_raw)) {
        raw_to_disp[] <- as.character(cats)
      }
    }
    strata_levels_disp <- paste0(cov_label, "\n", unname(raw_to_disp[strata_levels_raw]))
    strata_disp <- paste0(cov_label, "\n", unname(raw_to_disp[strata_raw]))
  } else if (is_numeric_cov && n_bins > 1L) {
    strata_levels_disp <- paste0(cov_label, "\n", strata_levels_raw)
    strata_disp <- paste0(cov_label, "\n", strata_raw)
  } else {
    strata_levels_disp <- "Overall"
    strata_disp <- rep("Overall", length(strata_raw))
  }

  strata_factor <- factor(strata_disp, levels = strata_levels_disp, ordered = TRUE)

  X_raw <- stats::model.matrix(cox_fit)
  beta_hat <- stats::coef(cox_fit)
  keep <- !is.na(beta_hat)
  beta_hat <- beta_hat[keep]
  X_raw <- X_raw[, keep, drop = FALSE]
  x_means <- cox_fit$means[names(beta_hat)]
  x_means[is.na(x_means)] <- 0
  X <- sweep(X_raw, 2L, x_means, FUN = "-")
  V <- stats::vcov(cox_fit)
  V <- V[names(beta_hat), names(beta_hat), drop = FALSE]
  L <- base::chol(V)

  bh <- survival::basehaz(cox_fit, centered = TRUE)
  if (!all(c("time", "hazard") %in% colnames(bh))) {
    cli::cli_abort("Internal error: unexpected output from {.fun survival::basehaz}.")
  }
  keep_h <- c(TRUE, diff(bh$hazard) > 0)
  haz_vals <- c(0, as.numeric(bh$hazard[keep_h]))
  haz_time <- c(0, as.numeric(bh$time[keep_h]))

  group_index <- split(seq_along(strata_factor), strata_factor)
  if (length(group_index) == 0L || any(vapply(group_index, length, integer(1)) == 0L)) {
    cli::cli_abort("At least one stratum has zero rows after preprocessing; cannot compute KM summaries.")
  }

  obs_curve <- .vpc_coxph_sim_km_to_grid(
    time = time_obs,
    status = event_obs,
    strata_factor = strata_factor,
    grid = grid,
    keep_ci = TRUE
  )

  worker_fn <- function(i) {
    z <- stats::rnorm(length(beta_hat))
    beta_b <- beta_hat + as.vector(crossprod(L, z))
    lp_b <- as.vector(X %*% beta_b)
    u <- stats::runif(length(lp_b))
    target <- -log(u) / exp(lp_b)
    evt_time <- .vpc_coxph_sim_inverse_hazard(target, haz_vals, haz_time)

    censor_time <- ifelse(event_obs == 0L, time_obs, Inf)
    sim_status <- as.integer(evt_time <= censor_time)
    sim_time <- pmin(evt_time, censor_time)

    sim_curve <- .vpc_coxph_sim_km_to_grid(
      time = sim_time,
      status = sim_status,
      strata_factor = strata_factor,
      grid = grid,
      keep_ci = FALSE
    )
    sim_curve$obs_est
  }

  rng <- .make_rng_streams(n_sim, seed)
  on.exit(rng$restore(), add = TRUE)
  streams <- rng$streams

  if (parallel) {
    sim_list <- future.apply::future_lapply(
      seq_len(n_sim), worker_fn, future.seed = streams
    )
  } else {
    sim_list <- vector("list", n_sim)
    for (i in seq_len(n_sim)) {
      assign(".Random.seed", streams[[i]], envir = .GlobalEnv)
      sim_list[[i]] <- worker_fn(i)
    }
  }

  sim_mat <- do.call(rbind, sim_list)
  qmat <- apply(sim_mat, 2L, stats::quantile, probs = probs, names = FALSE, na.rm = TRUE)
  sim_lo <- as.numeric(qmat[1L, ])
  sim_hi <- as.numeric(qmat[nrow(qmat), ])
  sim_mid <- if (has_median) as.numeric(qmat[2L, ]) else rep(NA_real_, ncol(sim_mat))

  out <- obs_curve
  out$sim_lo <- sim_lo
  out$sim_mid <- sim_mid
  out$sim_hi <- sim_hi
  out <- out[, c("strata", "time", "sim_lo", "sim_mid", "sim_hi", "obs_est", "obs_lo", "obs_hi")]

  if (!plot) {
    return(out)
  }

  time_col_name <- fit$metadata$time_col
  if (!is.null(time_col_name)) {
    time_display <- get_var_label(var_spec_obj, time_col_name)
    time_units <- get_var_units(var_spec_obj, time_col_name)
    x_label <- if (time_display != time_col_name && !is.na(time_units) && !is.null(time_units)) {
      paste0(time_display, " (", time_units, ")")
    } else if (time_display != time_col_name) {
      time_display
    } else {
      "Time"
    }
  } else {
    x_label <- "Time"
  }

  conf <- probs[length(probs)] - probs[1L]
  band_label <- paste0(round(conf * 100), "% prediction band")

  p <- ggplot2::ggplot(out, ggplot2::aes(x = .data$time)) +
    ggplot2::geom_ribbon(
      ggplot2::aes(ymin = .data$sim_lo, ymax = .data$sim_hi),
      alpha = 0.25, fill = "#2166AC"
    )

  if (has_median) {
    p <- p + ggplot2::geom_line(
      ggplot2::aes(y = .data$sim_mid),
      color = "#2166AC", linewidth = 0.8
    )
  }

  p <- p +
    ggplot2::geom_step(
      ggplot2::aes(y = .data$obs_est),
      color = "grey20", linewidth = 0.9
    ) +
    ggplot2::scale_y_continuous(
      limits = c(0, 1),
      labels = scales::percent_format(accuracy = 1)
    ) +
    ggplot2::labs(
      x = x_label,
      y = "Survival probability",
      subtitle = paste0("Observed KM vs simulated Cox curves (", band_label, ")")
    ) +
    ggplot2::theme_bw() +
    ggpubr::labs_pubr()

  if (length(levels(out$strata)) > 1L) {
    p <- p + ggplot2::facet_wrap(~ strata)
  }

  p
}

.vpc_coxph_sim_assert_supported_model <- function(cox_fit) {
  tt <- stats::terms(cox_fit)
  specials <- attr(tt, "specials")
  has_special <- function(name) {
    !is.null(specials[[name]]) && length(specials[[name]]) > 0L
  }

  if (has_special("tt") || has_special("strata") || has_special("cluster")) {
    cli::cli_abort(c(
      "{.fun vpc_coxph_sim} does not support time-dependent Cox formula specials in this release.",
      "x" = "Detected one of {.code tt()}, {.code strata()}, or {.code cluster()} in {.field final_model}.",
      "i" = "This is deferred to the v3 backlog."
    ))
  }

  y_mat <- cox_fit$y
  if (is.matrix(y_mat) && ncol(y_mat) > 2L) {
    cli::cli_abort(c(
      "{.fun vpc_coxph_sim} does not support start-stop {.code Surv()} responses in this release.",
      "x" = "Detected a counting-process response with more than two Surv columns.",
      "i" = "This is deferred to the v3 backlog."
    ))
  }
}

.vpc_coxph_sim_inverse_hazard <- function(target, haz_vals, haz_time) {
  out <- rep(Inf, length(target))
  max_h <- max(haz_vals)
  finite_idx <- which(is.finite(target) & target <= max_h)
  if (length(finite_idx) == 0L) {
    return(out)
  }

  out[finite_idx] <- stats::approx(
    x = haz_vals,
    y = haz_time,
    xout = target[finite_idx],
    method = "linear",
    ties = "ordered"
  )$y
  out
}

.vpc_coxph_sim_km_to_grid <- function(time, status, strata_factor, grid, keep_ci) {
  strata_levels <- levels(strata_factor)
  block_n <- length(grid)
  n_levels <- length(strata_levels)

  out <- data.frame(
    strata = factor(rep(strata_levels, each = block_n), levels = strata_levels, ordered = TRUE),
    time = rep(grid, times = n_levels),
    obs_est = NA_real_,
    obs_lo = NA_real_,
    obs_hi = NA_real_,
    stringsAsFactors = FALSE
  )

  for (j in seq_along(strata_levels)) {
    lev <- strata_levels[j]
    idx <- which(strata_factor == lev)
    sf <- survival::survfit(survival::Surv(time[idx], status[idx]) ~ 1)

    surv_t <- c(0, sf$time)
    surv_s <- c(1, sf$surv)
    eval_s <- .vpc_step_eval(grid, surv_t, surv_s)

    rows <- ((j - 1L) * block_n + 1L):(j * block_n)
    out$obs_est[rows] <- eval_s

    if (keep_ci) {
      lo <- c(1, sf$lower)
      hi <- c(1, sf$upper)
      out$obs_lo[rows] <- .vpc_step_eval(grid, surv_t, lo)
      out$obs_hi[rows] <- .vpc_step_eval(grid, surv_t, hi)
    }
  }

  if (!keep_ci) {
    out$obs_lo <- NA_real_
    out$obs_hi <- NA_real_
  }

  out
}

.vpc_step_eval <- function(grid, times, values) {
  idx <- findInterval(grid, times)
  idx[idx < 1L] <- 1L
  values[idx]
}
